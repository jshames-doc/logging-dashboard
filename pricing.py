"""Per-token rates for Devin Desktop models.

Rates live in pricing_data.json, generated by update_prices.py from
https://docs.devin.ai/desktop/models (Self-serve tier; models published only
on the Enterprise tier use that tier's rates). pricing_manual.json adds hand-entered
rates for models Devin doesn't publish; it is never overwritten, and published
rates win if a model later appears on the page. Both files are re-read
automatically when they change, so no server restart is needed. Rates are USD
per million tokens: label -> (input, output, cache_write, cache_read)

Manual entries may set "long_prompt" rates, applied to requests whose prompt
(input + cache write + cache read tokens) exceeds LONG_PROMPT_TOKENS.
"""

import json
import re
import sys
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA_PATH = ROOT / "pricing_data.json"
MANUAL_PATH = ROOT / "pricing_manual.json"
LONG_PROMPT_TOKENS = 100_000
COSTS = ("input", "output", "cache_write", "cache_read")

# DB generation_model slugs that match neither a published model_uid nor a label:
# plain slugs with no effort level, and legacy MODEL_* names. Every overridden
# label shares identical rates across its variants, so the choice is
# price-neutral.
OVERRIDES = {
    "MODEL_GOOGLE_GEMINI_3_0_FLASH_HIGH": "Gemini 3 Flash High",
    "MODEL_GOOGLE_GEMINI_3_0_FLASH_MEDIUM": "Gemini 3 Flash Medium",
    "MODEL_GOOGLE_GEMINI_3_0_FLASH_MINIMAL": "Gemini 3 Flash Minimal",
    "deepseek-v4": "DeepSeek V4 Pro High",
    "glm-5-2": "GLM-5.2 High",
    "nemotron-3-ultra-nvfp4": "Nemotron 3 Ultra High",
    "swe-1-7": "SWE-1.7 Medium",
}

# Rebuilt by _load() whenever either pricing file changes.
DATA, RATES, LONG_RATES, UIDS = {}, {}, {}, {}
_EXACT, _LOOSE, _RESOLVED = {}, {}, {}
_mtime, _lock = None, threading.Lock()

_TOK = re.compile(r"[a-z0-9]+")
_ALIAS = {"priority": "fast", "none": "no thinking"}
_BUILD = re.compile(r"(?:0[1-9]|1[0-2])(?:0[1-9]|[12][0-9]|3[01])")  # MMDD snapshot stamp


def _tokens(s):
    """Ordered lowercase alphanumeric tokens; 'priority' -> 'fast', 'none' -> 'no thinking'.
    Order and repeats matter: 'opus-5-5' (5.5) must not match 'Opus 5'."""
    toks = []
    for t in _TOK.findall(s.lower()):
        toks.extend(_ALIAS.get(t, t).split())
    return tuple(toks)


def _strip(toks):
    return tuple(t for t in toks if t != "thinking")


def _no_build(toks):
    """Drop a 4-digit MMDD build stamp (deepseek-v4-1-flash-1017-high has uid deepseek-v4-1-flash-high)."""
    return tuple(t for t in toks if not _BUILD.fullmatch(t))


def _read(path):
    try:
        mtime = path.stat().st_mtime
        data = json.loads(path.read_text(encoding="utf-8"))
        return mtime, data if isinstance(data, dict) else {"models": []}
    except (OSError, ValueError):
        return None, {"models": []}


def _models(data):
    """Well-formed entries from a pricing file's "models" list: dicts with a string label."""
    models = data.get("models")
    return ([m for m in models if isinstance(m, dict) and isinstance(m.get("label"), str)]
            if isinstance(models, list) else [])


def _uids(m):
    """Lowercased slugs for an entry: the 'uids' list (manual) or the single 'uid' (published)."""
    u = m.get("uids") or ([m["uid"]] if isinstance(m.get("uid"), str) else [])
    return [x.lower() for x in u if isinstance(x, str)] if isinstance(u, list) else []


def _mtimes():
    out = []
    for p in (DATA_PATH, MANUAL_PATH):
        try:
            out.append(p.stat().st_mtime)
        except OSError:
            out.append(None)
    return tuple(out)


def _load():
    """(Re)load pricing data if either file changed. Returns the merged data dict."""
    global _mtime
    with _lock:
        if _mtimes() == _mtime:
            return DATA
        m1, data = _read(DATA_PATH)
        m2, manual = _read(MANUAL_PATH)
        published = _models(data)
        labels = {m["label"] for m in published}
        uids = {u for m in published for u in _uids(m)}
        extra = [{**m, "uid": muids[0], "tier": "Manual"} for m in _models(manual)
                 if (muids := _uids(m)) and m["label"] not in labels and not set(muids) & uids]
        for d in (DATA, RATES, LONG_RATES, UIDS, _EXACT, _LOOSE, _RESOLVED):
            d.clear()
        DATA.update(data, models=published + extra)
        for m in published + extra:
            for uid in _uids(m):
                UIDS.setdefault(uid, m["label"])
            toks = _tokens(m["label"])
            _EXACT.setdefault(toks, m["label"])
            _LOOSE.setdefault(_strip(toks), m["label"])
            try:
                RATES.setdefault(m["label"], tuple(float(m[c]) for c in COSTS))
                lp = m.get("long_prompt")
                if lp:
                    LONG_RATES.setdefault(m["label"], tuple(float(lp[c]) for c in COSTS))
            except (KeyError, TypeError, ValueError, AttributeError):
                print(f"pricing: invalid rates for {m['label']!r} - treated as unpriced", file=sys.stderr)
        _mtime = (m1, m2)
    return DATA


def resolve(model_name):
    """Map a sessions.db generation_model slug to a priced label, or None.

    1. OVERRIDES; 2. exact published model_uid (most DB slugs are uids);
    3. ordered-token match against labels, then ignoring 'thinking'
       (e.g. gpt-5-6-luna-high -> GPT-5.6 Luna High Thinking), then also
       ignoring an MMDD build stamp (deepseek-v4-1-flash-1017-high ->
       DeepSeek V4.1 Flash High).
    """
    _load()
    if model_name in _RESOLVED:
        return _RESOLVED[model_name]
    label = OVERRIDES.get(model_name)
    if label not in RATES:
        label = UIDS.get(model_name.lower())
    if label is None:
        toks = _tokens(model_name)
        label = (_EXACT.get(toks) or _LOOSE.get(_strip(toks))
                 or _LOOSE.get(_strip(_no_build(toks))))
    _RESOLVED[model_name] = label
    return label


def price_info(model_name):
    """(label, (input, output, cache_write, cache_read) per Mtok) or (None, None)."""
    label = resolve(model_name)
    return label, RATES.get(label)


def cost(model_name, parts, long_parts=None):
    """(label, USD) for token counts {input, output, cache_write, cache_read}, or (None, None) if unpriced.

    long_parts is the subset of parts from requests over LONG_PROMPT_TOKENS; it is billed at the
    model's long-prompt rates when it has them, otherwise everything uses the base rates.
    """
    label, r = price_info(model_name)
    if not r:
        return None, None
    lr = LONG_RATES.get(label)
    long_parts = long_parts if lr and long_parts else dict.fromkeys(COSTS, 0)
    usd = sum((parts[c] - long_parts[c]) * r[i] + long_parts[c] * (lr or r)[i] for i, c in enumerate(COSTS))
    return label, usd / 1e6


def snapshot():
    """Pricing metadata + model list for the API."""
    data = _load()
    return {k: data.get(k) for k in ("source", "tier", "fallback_tier", "fetched")} | {"models": data.get("models", [])}


_load()
